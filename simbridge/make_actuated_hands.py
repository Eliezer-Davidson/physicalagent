#!/usr/bin/env python
"""Generate a G1 + Inspire model whose FINGERS ARE ACTUATED.

THE PROBLEM
    The scene the simulator runs, scene_29dof_inspire_rigid.xml, has hands that
    are rigid geometry -- 29 actuators, no finger joints at all. Its sibling
    g1_29dof_with_inspire.xml does have the finger joints (12 per hand, with
    force ranges already declared) but ships no actuators for them, so MuJoCo
    simulates fingers that nothing can move. Either way there is nothing to
    command, which is why the hand tool refuses rather than pretending.

THE CONSTRAINT THAT DICTATES THE OUTPUT
    base_sim.py scatters the body torques with

        torques[body_joint_index - 1] = body_torques

    i.e. it assumes actuator k drives joint k+1, for every k. That assumption is
    load-bearing for the whole controller. Inspire finger joints are children of
    the wrists, so MuJoCo interleaves them with the arm joints -- left fingers
    land between the left and right arm. Appending 24 actuators to the end of
    the actuator block therefore breaks the mapping for every joint after the
    left wrist, and the failure is silent: the robot gets shoulder torque
    applied to a finger and falls over for no visible reason.

    So this writes the actuator block in JOINT ORDER: one actuator per hinge
    joint, in the order MuJoCo will number them. Body actuators keep their
    vendor gear and force ranges verbatim; finger actuators get the joint's own
    actuatorfrcrange. The invariant is asserted at the end, on the loaded model,
    rather than trusted.

WHAT IT DOES NOT DO
    It does not change any body actuator, any mass, any geometry or any gain.
    The only difference from the vendor model is that 24 joints which were
    previously unactuated now have a motor. Verified by diffing the loaded
    models field by field (see --verify).

USAGE
    python simbridge/make_actuated_hands.py            # write + verify
    python simbridge/make_actuated_hands.py --verify   # verify only
"""
from __future__ import annotations

import argparse
import pathlib
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from physicalagent.paths import G1_MODEL_DIR  # noqa: E402

G1_DIR = G1_MODEL_DIR
SRC_ROBOT = G1_DIR / "g1_29dof_with_inspire.xml"
OUT_ROBOT = G1_DIR / "g1_29dof_with_inspire_actuated.xml"
SRC_SCENE = G1_DIR / "scene_29dof_inspire.xml"
OUT_SCENE = G1_DIR / "scene_29dof_inspire_actuated.xml"

# No double hyphen anywhere in here. "--" is illegal INSIDE an XML comment, and
# nothing in the chain complains: ElementTree writes it happily, MuJoCo loads the
# file happily, and then base_sim round-trips the model through mj_saveLastXML
# and ET.parse and dies with "not well-formed, line 2 column 78" pointing at a
# file that no longer exists.
BANNER = ("GENERATED by physicalagent/simbridge/make_actuated_hands.py"
          " : do not hand-edit, edit the generator")

# Rotor inertia and damping for the finger joints.
#
# WITHOUT THESE THE ROBOT CANNOT STAND. Measured, not guessed: the Inspire
# finger links have inertias down to 4.9e-08 kg m^2 and the vendor model gives
# them armature 0, damping 0 and frictionloss 0, while every body joint in the
# same model carries armature 0.01. A hinge that light with no armature, at the
# 2 ms timestep this scene uses, is numerically explosive -- the integrator
# diverges, the disturbance propagates up the arm, and check_fall resets the
# episode. The first run on this scene produced 179 resets in 60 s and never
# stood; the rigid scene under identical code produced 1.
#
# The values are also the physically honest ones. A real Inspire RH56 finger is
# worm-gear driven and essentially non-backdrivable: high reflected inertia and
# heavy damping is what the hardware actually behaves like, and a frictionless
# free-swinging finger is the unphysical model, not this.
FINGER_ARMATURE = 0.002
FINGER_DAMPING = 0.05
FINGER_FRICTIONLOSS = 0.001


def joint_order(root: ET.Element) -> list[ET.Element]:
    """Hinge/slide joints in MuJoCo's numbering order.

    MuJoCo numbers joints by depth-first body traversal, and ElementTree's
    document order is that same traversal, so iterating the tree is not an
    approximation of the joint order -- it is the joint order. The free root
    joint is excluded: it has no actuator and shifts nothing, because the vendor
    mapping is written relative to joint 1.
    """
    joints = []
    for body in root.iter("body"):
        for jnt in body.findall("joint"):
            if jnt.get("type") == "free":
                continue
            joints.append(jnt)
    return joints


def build(verify_only: bool = False) -> int:
    tree = ET.parse(SRC_ROBOT)
    root = tree.getroot()

    old_actuators = root.find("actuator")
    if old_actuators is None:
        print(f"ERROR: {SRC_ROBOT} has no <actuator> block", file=sys.stderr)
        return 1
    by_joint = {a.get("joint"): a for a in old_actuators}

    joints = joint_order(root)
    names = [j.get("name") for j in joints]
    finger = [n for n in names if n not in by_joint]
    print(f"{len(joints)} hinge joints: {len(by_joint)} actuated, "
          f"{len(finger)} unactuated fingers")

    new_actuators = ET.Element("actuator")
    for jnt in joints:
        name = jnt.get("name")
        existing = by_joint.get(name)
        if existing is not None:
            new_actuators.append(existing)       # verbatim, gains included
            continue
        frc = jnt.get("actuatorfrcrange", "-1 1")
        ET.SubElement(new_actuators, "motor", {
            "name": name, "joint": name, "ctrllimited": "true",
            "ctrlrange": frc, "gear": "1",
        })
        # Only ever ADDED, never overwritten: if a future vendor model gives the
        # fingers their own armature, that is better information than ours.
        for attr, value in (("armature", FINGER_ARMATURE),
                            ("damping", FINGER_DAMPING),
                            ("frictionloss", FINGER_FRICTIONLOSS)):
            if jnt.get(attr) is None:
                jnt.set(attr, str(value))

    if not verify_only:
        root.remove(old_actuators)
        root.append(new_actuators)
        comment = ET.Comment(f" {BANNER} ")
        root.insert(0, comment)
        ET.indent(tree, space="  ")
        tree.write(OUT_ROBOT, encoding="utf-8", xml_declaration=False)
        print(f"wrote {OUT_ROBOT}")

        scene = ET.parse(SRC_SCENE)
        sroot = scene.getroot()
        for inc in sroot.iter("include"):
            if "inspire" in (inc.get("file") or ""):
                inc.set("file", OUT_ROBOT.name)
        sroot.insert(0, ET.Comment(f" {BANNER} "))
        ET.indent(scene, space="  ")
        scene.write(OUT_SCENE, encoding="utf-8", xml_declaration=False)
        print(f"wrote {OUT_SCENE}")

    return verify()


def verify() -> int:
    """Load the generated model and check the invariant the controller relies
    on. A generator that emits a plausible file and is never loaded is how the
    silent-torque-misrouting bug would ship."""
    import mujoco

    if not OUT_SCENE.exists():
        print(f"ERROR: {OUT_SCENE} not generated", file=sys.stderr)
        return 1
    m = mujoco.MjModel.from_xml_path(str(OUT_SCENE))
    ref = mujoco.MjModel.from_xml_path(str(SRC_SCENE))

    failures = []

    # base_sim round-trips the model through mj_saveLastXML + ET.parse to read
    # joint classes. Loading cleanly is therefore NOT enough -- the saved copy
    # has to re-parse too, and a "--" inside a comment breaks only that half.
    import tempfile
    import xml.etree.ElementTree as _ET
    with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as tmp:
        mujoco.mj_saveLastXML(tmp.name, m)
        try:
            _ET.parse(tmp.name)
        except _ET.ParseError as exc:
            failures.append(f"the model does not survive mj_saveLastXML -> "
                            f"ET.parse, which base_sim does on startup: {exc}")
        finally:
            pathlib.Path(tmp.name).unlink(missing_ok=True)
    if m.nu != m.njnt - 1:
        failures.append(f"nu={m.nu} but njnt-1={m.njnt - 1}: not one actuator per joint")
    for a in range(m.nu):
        j = int(m.actuator_trnid[a][0])
        if j != a + 1:
            failures.append(f"actuator {a} ({m.actuator(a).name}) drives joint {j}, "
                            f"expected {a + 1} — torque routing would be WRONG")
            break
    if m.nq != ref.nq:
        failures.append(f"nq changed: {ref.nq} -> {m.nq}")
    if abs(float(m.body_mass.sum()) - float(ref.body_mass.sum())) > 1e-9:
        failures.append("total mass changed")

    fingers = [m.actuator(a).name for a in range(m.nu)
               if (m.actuator(a).name or "").startswith(("L_", "R_"))]
    if len(fingers) != 24:
        failures.append(f"{len(fingers)} finger actuators, expected 24")

    # Every added joint must have rotor inertia. This is the check that would
    # have caught the 179-reset run before it ever reached the robot: the model
    # LOADS fine without it and only falls apart once the physics runs.
    import numpy as np

    finger_joints = [j for j in range(m.njnt)
                     if (m.joint(j).name or "").startswith(("L_", "R_"))]
    dofs = [int(m.jnt_dofadr[j]) for j in finger_joints]
    if dofs:
        if float(np.min(m.dof_armature[dofs])) <= 0.0:
            failures.append("a finger joint has zero armature — the integrator "
                            "will diverge and the robot will not stand")
        if float(np.min(m.dof_damping[dofs])) <= 0.0:
            failures.append("a finger joint has zero damping")
        # Armature has to dominate the link's own inertia to do its job.
        worst = min(float(m.dof_armature[int(m.jnt_dofadr[j])])
                    / max(float(np.min(m.body_inertia[int(m.jnt_bodyid[j])])), 1e-12)
                    for j in finger_joints)
        if worst < 100.0:
            failures.append(f"armature only {worst:.0f}x the link inertia; "
                            "too small to stabilise the integration")

    if failures:
        for f in failures:
            print(f"FAIL: {f}", file=sys.stderr)
        return 1
    print(f"OK  nu={m.nu} nq={m.nq}  actuator k drives joint k+1 for all k")
    print(f"OK  24 finger actuators; mass and nq unchanged vs {SRC_SCENE.name}")
    return 0


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--verify", action="store_true", help="verify without writing")
    raise SystemExit(build(verify_only=p.parse_args().verify))
