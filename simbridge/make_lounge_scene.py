#!/usr/bin/env python
"""Compose the SONIC actuated G1 scene with a photo-reconstructed furnished lounge.

INPUT FROM ANOTHER PROJECT (not shipped with this repo)
    The furnished room comes from a photo-to-MuJoCo scene reconstruction tool
    that is a separate, unpublished project of the same author -- see
    THIRD_PARTY_NOTICES.md section 2. Point SCENE_SOURCE_ROOT at its output
    tree; this generator expects, relative to that root:

        out/<scene_name>/mujoco/<scene_name>.xml   an MJCF with one body per
                                                   object, meshes beside it

    Without it, the flat SONIC scene still works -- only the furnished variant
    is unavailable.

WHY A GENERATOR
    The lounge XML is a read-only artifact of that other project, the SONIC wrapper is
    a generated vendor-side file, and the merge has six known hazards (duplicate
    floor, meshdir conflict, symlinked assets, origin clearance, name filters,
    qpos ordering). A generator turns each hazard into an assert on the LOADED
    model; hand-merging turns them into hopes. Template: make_actuated_hands.py.

WHAT IT EMITS (untracked, vendor g1/ dir, regenerable)
    scene_29dof_inspire_lounge.xml   wrapper + robot include + 5 furniture bodies
    lounge_assets/                   dereferenced .obj copies (absolute paths in
                                     the XML: the merged model has ONE meshdir,
                                     the robot's, so furniture files must not
                                     rely on it)

WHY office_lounge_clean, NOT office_lounge_ground2 (measured 2026-08-12)
    ground2 is the reconstruction's "placement only" run: poses were never physically
    settled and black_backpack_0 starts airborne, tumbling ~3.2 m in 1 s of
    bare mj_step (same failure reproduces unmodified in ground2 itself). clean
    is the CEM-settled sibling run: every body but the backpack settles to
    <=1.3 cm over 3 s. The backpack has no equilibrium pose in ANY variant of
    this scene family, so it is excluded from extraction (see FURNITURE_BODIES).

PLACEMENT
    Every lounge body ships pos="0 0 0" with placement baked into mesh vertex
    coordinates; the cluster sits ~0.5 m from the origin, inside the elastic
    band's hang/respawn cylinder. All five extracted bodies get one shared -y
    shift so the nearest collision geom clears CLEAR_RADIUS_M.

USAGE
    ${WBC_ROOT:-$HOME/GR00T-WholeBodyControl}/.venv_sim/bin/python \
        simbridge/make_lounge_scene.py            # write + verify
    ... --verify                                  # verify existing output only
"""
from __future__ import annotations

import argparse
import math
import pathlib
import re
import shutil
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
from physicalagent.paths import G1_MODEL_DIR, SCENE_SOURCE_ROOT  # noqa: E402

G1_DIR = G1_MODEL_DIR
SRC_SCENE = G1_DIR / "scene_29dof_inspire_actuated.xml"
LOUNGE_SRC = SCENE_SOURCE_ROOT / "out" / "office_lounge_clean" / "mujoco" / "office_lounge.xml"
OUT_SCENE = G1_DIR / "scene_29dof_inspire_lounge.xml"
ASSETS_OUT = G1_DIR / "lounge_assets"

CLEAR_RADIUS_M = 1.2      # band hang + fall-respawn cylinder around the origin
SETTLE_STEPS = 500        # 1.0 s at the model's 2 ms timestep
SETTLE_TOL_M = 0.02       # per-body drift allowed while settling

# One hyphen only in generated comments: "--" is illegal inside XML comments and
# base_sim round-trips the model through mj_saveLastXML + ET.parse on startup.
BANNER = ("GENERATED by simbridge/make_lounge_scene.py"
          " : do not hand-edit, edit the generator. Furniture from an external"
          " photo reconstruction, office_lounge_clean (read-only source).")

# MUST equal simbridge/sidecar.py _ROBOT_HINTS — pinned by
# tests/test_lounge_scene_gen.py. A furniture name matching one of these becomes
# invisible to describe_scene and transparent to scan.
_ROBOT_HINTS = ("pelvis", "waist", "torso", "hip", "knee", "ankle", "shoulder",
                "elbow", "wrist", "hand", "thumb", "index", "middle", "ring",
                "pinky", "link", "head", "logo", "imu")

# base_sim.py:285-299 asserts on joint names matching these; furniture joints
# are unnamed freejoints, so this is belt and braces.
LEG_JOINT_RE = re.compile(r"hip|knee|ankle|waist|shoulder|elbow|wrist")

# All six bodies the source scene family ships. Used ONLY for the staleness
# check in build(): a body that is neither KNOWN nor extracted means the
# source scene changed shape and the extraction list needs a human look.
KNOWN_BODIES = ("grey_and_yellow_bench_0", "white_round_table_0",
                "black_laptop_1_0", "black_backpack_0", "black_laptop_2_0",
                "black_thermos_0")

# Extracted bodies. black_backpack_0 is deliberately excluded: measured
# 2026-08-12, it has no settled pose in ANY reconstructed variant of this scene
# (see the module docstring). Everything else keys off this tuple.
FURNITURE_BODIES = ("grey_and_yellow_bench_0", "white_round_table_0",
                    "black_laptop_1_0", "black_laptop_2_0",
                    "black_thermos_0")


def needed_shift_m(clearance_now: float, wanted: float = CLEAR_RADIUS_M) -> float:
    """How far to move the cluster (whole centimetres, rounded up)."""
    gap = wanted - clearance_now
    if gap <= 0:
        return 0.0
    return math.ceil(gap * 100.0) / 100.0


def _min_clearance(model, data, body_ids) -> float:
    """Horizontal distance from the origin to the nearest collision geom of the
    given bodies, bounding-sphere conservative."""
    import numpy as np

    best = float("inf")
    for g in range(model.ngeom):
        if int(model.geom_bodyid[g]) not in body_ids:
            continue
        if int(model.geom_contype[g]) == 0 and int(model.geom_conaffinity[g]) == 0:
            continue                       # visual-only geom
        x, y = float(data.geom_xpos[g][0]), float(data.geom_xpos[g][1])
        best = min(best, math.hypot(x, y) - float(model.geom_rbound[g]))
    return best


def _measure_source_clearance() -> float:
    import mujoco

    m = mujoco.MjModel.from_xml_path(str(LOUNGE_SRC))
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    ids = {m.body(n).id for n in FURNITURE_BODIES}
    return _min_clearance(m, d, ids)


def build() -> int:
    lounge = ET.parse(LOUNGE_SRC).getroot()
    wrapper = ET.parse(SRC_SCENE)
    wroot = wrapper.getroot()

    # -- name checks against the ROBOT include, before anything is written
    include = wroot.find("include")
    robot_root = ET.parse(G1_DIR / include.get("file")).getroot()
    robot_names = {b.get("name") for b in robot_root.iter("body")}
    for name in FURNITURE_BODIES:
        if name in robot_names:
            print(f"ERROR: furniture body '{name}' collides with a robot body",
                  file=sys.stderr)
            return 1
        if any(h in name for h in _ROBOT_HINTS):
            print(f"ERROR: '{name}' matches a sidecar robot hint", file=sys.stderr)
            return 1

    shift = needed_shift_m(_measure_source_clearance())
    print(f"cluster shift: {shift:.2f} m in -y")

    # -- assets: meshes only (the lounge floor/skybox/materials are dropped with
    #    the floor geom). Copies dereference the source tree's symlink farm.
    #    Filtered by FURNITURE_BODIES: the backpack's 17 meshes are neither
    #    copied nor declared. A declared mesh whose file is missing would
    #    break the compile; an unreferenced declared mesh is dead weight.
    ASSETS_OUT.mkdir(parents=True, exist_ok=True)
    wasset = wroot.find("asset")
    for mesh in lounge.find("asset").findall("mesh"):
        fname = mesh.get("file")
        if not any(fname.startswith(b) for b in FURNITURE_BODIES):
            continue                       # e.g. black_backpack_0_col08.obj
        src = LOUNGE_SRC.parent / "assets" / fname
        dst = ASSETS_OUT / fname
        shutil.copy(src, dst)              # follows symlinks
        if dst.stat().st_size == 0:
            print(f"ERROR: empty asset {dst}", file=sys.stderr)
            return 1
        mesh.set("file", str(dst))         # absolute: immune to the robot meshdir
        wasset.append(mesh)

    # -- default classes, renamed so nothing merges with robot classes
    for dflt in lounge.find("default").findall("default"):
        dflt.set("class", "lounge_" + dflt.get("class"))
        wroot.find("default").append(dflt)

    # -- furniture bodies, shifted, classes re-pointed
    wbody = wroot.find("worldbody")
    for body in lounge.find("worldbody").findall("body"):
        name = body.get("name")
        if name not in FURNITURE_BODIES:
            if name in KNOWN_BODIES:
                print(f"skipping {name}: no settled pose exists in any "
                      "source variant")
                continue
            print(f"ERROR: unexpected body '{name}' in the lounge "
                  "source; the extraction list is stale", file=sys.stderr)
            return 1
        px, py, pz = (float(v) for v in body.get("pos").split())
        body.set("pos", f"{px:.6f} {py - shift:.6f} {pz:.6f}")
        for geom in body.findall("geom"):
            if geom.get("class"):
                geom.set("class", "lounge_" + geom.get("class"))
        for jnt in body.findall("joint"):
            if LEG_JOINT_RE.search(jnt.get("name") or ""):
                print(f"ERROR: joint name would trip base_sim's leg-name assert",
                      file=sys.stderr)
                return 1
        wbody.append(body)                 # AFTER the robot include: qpos order

    wroot.insert(0, ET.Comment(f" {BANNER} "))
    ET.indent(wrapper, space="  ")
    tmp = OUT_SCENE.with_suffix(".xml.tmp")
    wrapper.write(tmp, encoding="utf-8", xml_declaration=False)
    rc = verify(scene_path=tmp)
    if rc != 0:
        tmp.unlink(missing_ok=True)
        return rc
    tmp.replace(OUT_SCENE)                 # atomic: no half-written scene
    print(f"wrote {OUT_SCENE}")
    return 0


def verify(scene_path: pathlib.Path = OUT_SCENE) -> int:
    """Every merge hazard, asserted on the LOADED model."""
    import mujoco
    import numpy as np

    if not scene_path.exists():
        print(f"ERROR: {scene_path} not generated", file=sys.stderr)
        return 1
    m = mujoco.MjModel.from_xml_path(str(scene_path))
    ref = mujoco.MjModel.from_xml_path(str(SRC_SCENE))
    failures = []

    # base_sim round-trip (idiom from make_actuated_hands.verify)
    import tempfile
    with tempfile.NamedTemporaryFile(suffix=".xml", delete=False) as tmp:
        mujoco.mj_saveLastXML(tmp.name, m)
        try:
            ET.parse(tmp.name)
        except ET.ParseError as exc:
            failures.append(f"does not survive mj_saveLastXML + ET.parse: {exc}")
        finally:
            pathlib.Path(tmp.name).unlink(missing_ok=True)

    if m.nu != ref.nu:
        failures.append(f"nu changed {ref.nu} -> {m.nu}: furniture grew actuators")
    if m.nq != ref.nq + 7 * len(FURNITURE_BODIES):
        failures.append(f"nq {m.nq}, expected {ref.nq + 7 * len(FURNITURE_BODIES)}")
    root_j = m.joint("floating_base_joint")
    if int(m.jnt_qposadr[root_j.id]) != 0:
        failures.append("robot free joint no longer owns qpos[0:7]")
    lounge_ids = {m.body(n).id for n in FURNITURE_BODIES}
    for j in range(m.njnt):
        if int(m.jnt_bodyid[j]) in lounge_ids and int(m.jnt_qposadr[j]) < ref.nq:
            failures.append("a furniture joint landed inside the robot's qpos block")
            break
    planes = [g for g in range(m.ngeom)
              if int(m.geom_type[g]) == int(mujoco.mjtGeom.mjGEOM_PLANE)]
    if len(planes) != 1:
        failures.append(f"{len(planes)} floor planes, expected exactly 1")
    thermos = float(m.body("black_thermos_0").mass[0])
    if not 0.02 <= thermos <= 0.06:
        failures.append(f"thermos mass {thermos:.3f} kg outside the 20-60 g band")

    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    clear = _min_clearance(m, d, lounge_ids)
    if clear < CLEAR_RADIUS_M:
        failures.append(f"origin clearance {clear:.2f} m < {CLEAR_RADIUS_M}")

    start = {n: np.array(d.body(n).xpos) for n in FURNITURE_BODIES}
    for _ in range(SETTLE_STEPS):
        mujoco.mj_step(m, d)               # robot collapses uncontrolled: fine,
    for n in FURNITURE_BODIES:             # only furniture drift is judged here
        drift = float(np.linalg.norm(np.array(d.body(n).xpos) - start[n]))
        if drift > SETTLE_TOL_M:
            failures.append(f"{n} drifted {drift * 100:.1f} cm in 1 s unpoked")

    if failures:
        for f in failures:
            print(f"FAIL: {f}", file=sys.stderr)
        return 1
    print(f"OK  nu={m.nu} nq={m.nq} clearance={clear:.2f} m; furniture settled")
    return 0


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--verify", action="store_true", help="verify without writing")
    a = p.parse_args()
    raise SystemExit(verify() if a.verify else build())
